TEST_F(TuningOutputTest, RegistryParams_YamlGeneration) {
  const auto& search = ConfigManager::instance().search();
  const auto& eval   = ConfigManager::instance().eval();
  auto params = TuningParameter::buildFromRegistry(search, eval);

  // Modify a few params to simulate tuning
  for (auto& p : params) {
    if (p.name == "TEMPO") {
      p.currentValue = 30;
    }
    if (p.name == "KING_SAFETY_TABLE[5]") {
      p.currentValue = 55;
    }
  }

  const auto yaml = TuningOutput::generateParamsYaml(params, 1.196);

  // Should contain coalesced KING_SAFETY_TABLE
  EXPECT_TRUE(yaml.find("KING_SAFETY_TABLE:") != std::string::npos);
  // Should not have individual element notation
  EXPECT_TRUE(yaml.find("KING_SAFETY_TABLE[") == std::string::npos);
  // Should contain TEMPO
  EXPECT_TRUE(yaml.find("TEMPO: 30") != std::string::npos);
}

TEST_F(TuningOutputTest, RegistryParams_ComparisonReport) {
  const auto& search = ConfigManager::instance().search();
  const auto& eval   = ConfigManager::instance().eval();
  auto params = TuningParameter::buildFromRegistry(search, eval);

  // Modify some params
  for (auto& p : params) {
    if (p.configName == "TEMPO") {
      p.currentValue = p.originalValue - 2;
    }
  }

  const auto report = TuningOutput::generateComparisonReport(params);

  EXPECT_TRUE(report.find("TEMPO") != std::string::npos);
  EXPECT_TRUE(report.find("Total parameters:") != std::string::npos);
  // Verify the correct total count matches buildFromRegistry
  const auto expectedCount = std::format("Total parameters:  {}", params.size());
  EXPECT_TRUE(report.find(expectedCount) != std::string::npos)
    << "Expected: " << expectedCount << "\nReport:\n" << report.substr(0, 500);
}

