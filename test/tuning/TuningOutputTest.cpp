class TuningOutputTest : public testing::Test {
public:
  static void SetUpTestSuite() {
    NEWLINE;
    init::init();
    NEWLINE;
  }

protected:
  /// Helper: create a small param vector for testing
  static std::vector<TuningParameter> makeTestParams() {
    std::vector<TuningParameter> params;

    // Scalar param — changed
    TuningParameter p1;
    p1.name          = "TEMPO";
    p1.configName    = "TEMPO";
    p1.originalValue = 34;
    p1.currentValue  = 30;
    p1.arrayIndex    = -1;
    p1.arraySize     = 0;
    params.push_back(p1);

    // Scalar param — unchanged
    TuningParameter p2;
    p2.name          = "ISOLATED_PAWN_MID_WEIGHT";
    p2.configName    = "ISOLATED_PAWN_MID_WEIGHT";
    p2.originalValue = -10;
    p2.currentValue  = -10;
    p2.arrayIndex    = -1;
    p2.arraySize     = 0;
    params.push_back(p2);

    // Scalar param — sign flip
    TuningParameter p3;
    p3.name          = "BLOCKED_PAWN_MID_WEIGHT";
    p3.configName    = "BLOCKED_PAWN_MID_WEIGHT";
    p3.originalValue = -2;
    p3.currentValue  = 1;
    p3.arrayIndex    = -1;
    p3.arraySize     = 0;
    params.push_back(p3);

    // Scalar param — zeroed out
    TuningParameter p4;
    p4.name          = "SPACE_BONUS_END";
    p4.configName    = "SPACE_BONUS_END";
    p4.originalValue = 1;
    p4.currentValue  = 0;
    p4.arrayIndex    = -1;
    p4.arraySize     = 0;
    params.push_back(p4);

    // Array param — 3 elements
    for (int i = 0; i < 3; ++i) {
      TuningParameter pa;
      pa.name          = "TEST_ARRAY[" + std::to_string(i) + "]";
      pa.configName    = "TEST_ARRAY";
      pa.originalValue = i * 10;       // 0, 10, 20
      pa.currentValue  = i * 10 + 5;   // 5, 15, 25
      pa.arrayIndex    = i;
      pa.arraySize     = 3;
      params.push_back(pa);
    }

    return params;
  }

  /// Helper: read a file into a string
  static std::string readFile(const std::string& path) {
    std::ifstream ifs(path);
    return {std::istreambuf_iterator<char>(ifs), std::istreambuf_iterator<char>()};
  }
};

// =========================================================================
// YAML generation tests
// =========================================================================

TEST_F(TuningOutputTest, GenerateParamsYaml_ContainsHeader) {
  const auto params = makeTestParams();
  const auto yaml = TuningOutput::generateParamsYaml(params, 1.196);

  EXPECT_TRUE(yaml.find("FrankyCPP Tuned Evaluation Parameters") != std::string::npos);
  EXPECT_TRUE(yaml.find("Generated by Texel Tuner") != std::string::npos);
  EXPECT_TRUE(yaml.find("1.196") != std::string::npos) << "K value should be in header";
}

TEST_F(TuningOutputTest, GenerateParamsYaml_ScalarParams) {
  const auto params = makeTestParams();
  const auto yaml = TuningOutput::generateParamsYaml(params);

  // Scalar params should appear as "KEY: value"
  EXPECT_TRUE(yaml.find("TEMPO: 30") != std::string::npos);
  EXPECT_TRUE(yaml.find("ISOLATED_PAWN_MID_WEIGHT: -10") != std::string::npos);
  EXPECT_TRUE(yaml.find("BLOCKED_PAWN_MID_WEIGHT: 1") != std::string::npos);
  EXPECT_TRUE(yaml.find("SPACE_BONUS_END: 0") != std::string::npos);
}

TEST_F(TuningOutputTest, GenerateParamsYaml_ArrayCoalesced) {
  const auto params = makeTestParams();
  const auto yaml = TuningOutput::generateParamsYaml(params);

  // Array elements should be coalesced into single comma-separated line
  EXPECT_TRUE(yaml.find("TEST_ARRAY: 5,15,25") != std::string::npos)
    << "Array should be coalesced. YAML:\n" << yaml;

  // Individual array element names should NOT appear
  EXPECT_TRUE(yaml.find("TEST_ARRAY[0]") == std::string::npos);
  EXPECT_TRUE(yaml.find("TEST_ARRAY[1]") == std::string::npos);
}

TEST_F(TuningOutputTest, GenerateParamsYaml_EmptyParams) {
  // ReSharper disable once CppVariableCanBeMadeConstexpr
  const std::vector<TuningParameter> empty;
  const auto yaml = TuningOutput::generateParamsYaml(empty);

  // Should still have header but no param lines
  EXPECT_TRUE(yaml.find("FrankyCPP Tuned Evaluation Parameters") != std::string::npos);
  EXPECT_TRUE(yaml.find("TEMPO") == std::string::npos);
}

TEST_F(TuningOutputTest, WriteParamsYaml_CreatesFile) {
  const auto params = makeTestParams();
  const std::string path = "test_tuning_output.yaml";

  TuningOutput::writeParamsYaml(path, params, 1.2);
  ASSERT_TRUE(std::filesystem::exists(path));

  const auto content = readFile(path);
  EXPECT_TRUE(content.find("TEMPO: 30") != std::string::npos);
  EXPECT_TRUE(content.find("TEST_ARRAY: 5,15,25") != std::string::npos);

  std::filesystem::remove(path);
}

TEST_F(TuningOutputTest, WriteParamsYaml_BadPath) {
  const auto params = makeTestParams();
  EXPECT_THROW(TuningOutput::writeParamsYaml("/nonexistent/dir/file.yaml", params), std::runtime_error);
}

